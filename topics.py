# -*- coding: utf-8 -*-
"""Тема посту → послуга в боті. Кнопка під постом веде одразу до потрібної послуги."""
import re

BOT = "CooLaw007_bot"
# Порядок важливий: вузькі теми перед широкими.
ПРАВИЛА = [
    (r"ст(атт[яі])?\.?\s*130|п.ян\w* за кермом|нетверез|драгер|огляд на стан", "s130"),
    (r"122-4|залиш\w+ місц\w+ ДТП", "s1224"),
    (r"ст(атт[яі])?\.?\s*124|\bДТП\b", "s124"),
    (r"митн", "customs"),
    (r"обшук", "search"),
    (r"арешт\w* (рахунк|картк|кошт)|заблок\w+ (картк|рахун)", "arrest"),
    (r"реєстр\w* боржник", "registry"),
    (r"виконавч\w+ напис", "writ"),
    (r"банкрут", "bankruptcy"),
    (r"кредит|мікрокредит|\bМФО\b|колектор", "collectors"),
    (r"додатков\w+ витрат|аліменти|аліментів|аліментн", "alimony"),
    (r"позбавлен\w+ батьківськ", "pbp"),
    (r"батьківств", "paternity"),
    (r"місц\w+ проживання дитин|з ким (буде )?жити", "residence"),
    (r"виїзд\w* дитин|вивез\w+ дитин", "travel"),
    (r"поділ\w* майна|спільн\w+ майн", "property"),
    (r"розлуч|розірван\w+ шлюб|шлюб", "divorce"),
    (r"спадщин|спадкоєм|заповіт|спадков|у спадок", "inheritance"),
    (r"встановлен\w+ факт|факт смерті", "facts"),
    (r"самобуд|самочинн", "selfbuild"),
    (r"земельн|нерухом|паркан|квартир", "land"),
    (r"родин\w+ загибл|зник\w* безвісти|15 млн", "family_pay"),
    (r"військов|бойов\w+ виплат|грошов\w+ забезпечен", "pay"),
    (r"партнер\w* у бізнес|партнерств", "partners"),
    (r"кримінальн|підозр|слідч|допит", "crim"),
]
_СКОМПІЛЬОВАНІ = [(re.compile(p, re.I), s) for p, s in ПРАВИЛА]


def topic_for(текст: str) -> str:
    """Ідентифікатор послуги або порожній рядок, якщо тема незрозуміла."""
    for шаблон, послуга in _СКОМПІЛЬОВАНІ:
        if шаблон.search(текст or ""):
            return послуга
    return ""


def bot_link(послуга: str = "") -> str:
    return f"https://t.me/{BOT}" + (f"?start=s_{послуга}" if послуга else "")
